def normalize_language(language: str | None) -> str:
    return language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def toggle_language(language: str | None) -> str:
    return "pt" if normalize_language(language) == "en" else "en"


def t(language: str | None, key: str, **params) -> str:
    language = normalize_language(language)
    template = TRANSLATIONS.get(language, {}).get(key) or TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    try:
        return template.format(**params)
    except (KeyError, ValueError):
        return template
